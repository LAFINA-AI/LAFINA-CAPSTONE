/**
 * Skill handoff (ADR-041): what LAFINA may open in the Skills tab, and how.
 *
 * A launch is navigation, not a write. It names one skill from this fixed
 * list and one allowed action. Free text (a topic) is only ever used to
 * pre-fill a field; nothing here generates, records or saves by itself. The
 * one action that starts something is a Pomodoro "start", which is local,
 * reversible and shown with Pause on arrival.
 */

/** Skills LAFINA can open. The ids are the Skills tab's own route ids. */
export const LAUNCHABLE_SKILLS = [
  'pomodoro',
  'flashcards',
  'quiz',
  'summarizer',
  'materials',
  'docgen',
  'meetings',
  'gwa',
  'alarms',
  'todo',
  'notes',
  'hub',
] as const;
export type LaunchableSkill = (typeof LAUNCHABLE_SKILLS)[number];

export const SKILL_ACTIONS = [
  'open',
  'start',
  'break',
  'create',
  'review',
] as const;
export type SkillAction = (typeof SKILL_ACTIONS)[number];

/** A request to open one skill, already validated. */
export interface SkillLaunch {
  skill: LaunchableSkill;
  action: SkillAction;
  /** Pomodoro break length. */
  breakKind?: 'short' | 'long';
  /** Quiz questions or flashcards asked for. */
  count?: number;
  /** Documents: the topic, to pre-fill the prompt (never generated by itself). */
  topic?: string;
  /** A saved lesson the student named, pre-selected as the source. */
  materialId?: string;
}

/** A launch as the Skills tab receives it: once, by its id. */
export interface SkillLaunchRequest extends SkillLaunch {
  id: string;
}

interface CatalogEntry {
  /** How LAFINA says its name. */
  name: string;
  actions: readonly SkillAction[];
  /** Needs Online Mode (an account and the internet) for its main use. */
  online?: boolean;
}

export const SKILL_CATALOG: Readonly<Record<LaunchableSkill, CatalogEntry>> = {
  pomodoro: {name: 'Pomodoro', actions: ['open', 'start', 'break']},
  flashcards: {name: 'Flashcards', actions: ['open', 'create', 'review']},
  quiz: {name: 'Quiz maker', actions: ['open', 'create']},
  summarizer: {
    name: 'the Summarizer',
    actions: ['open', 'create'],
    online: true,
  },
  materials: {name: 'Lesson Q&A', actions: ['open', 'create']},
  docgen: {
    name: 'Create with LAFINA',
    actions: ['open', 'create'],
    online: true,
  },
  meetings: {name: 'Meetings', actions: ['open']},
  gwa: {name: 'the GWA calculator', actions: ['open']},
  alarms: {name: 'Alarms', actions: ['open']},
  todo: {name: 'your To-do list', actions: ['open']},
  notes: {name: 'Notes', actions: ['open']},
  hub: {name: 'Skills', actions: ['open']},
};

const MAX_TOPIC = 200;
const MAX_COUNT = 30;

const isSkill = (value: unknown): value is LaunchableSkill =>
  typeof value === 'string' &&
  (LAUNCHABLE_SKILLS as readonly string[]).includes(value);

const isAction = (value: unknown): value is SkillAction =>
  typeof value === 'string' &&
  (SKILL_ACTIONS as readonly string[]).includes(value);

/** Control characters and markup are dropped; a topic is plain words only. */
const cleanTopic = (value: unknown): string | undefined => {
  if (typeof value !== 'string') return undefined;
  const text = value
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f\u007f<>{}[\]`]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, MAX_TOPIC);
  return text || undefined;
};

/**
 * Checks a launch against the allowlist. Anything unknown is refused, and an
 * action a skill does not have falls back to opening it.
 */
export const validateSkillLaunch = (
  input: Partial<Record<keyof SkillLaunch, unknown>>,
): SkillLaunch | null => {
  if (!isSkill(input.skill)) return null;
  const entry = SKILL_CATALOG[input.skill];
  const action: SkillAction =
    isAction(input.action) && entry.actions.includes(input.action)
      ? input.action
      : 'open';
  const launch: SkillLaunch = {skill: input.skill, action};
  if (action === 'break')
    launch.breakKind = input.breakKind === 'long' ? 'long' : 'short';
  const count = Number(input.count);
  if (
    (input.skill === 'quiz' || input.skill === 'flashcards') &&
    Number.isInteger(count) &&
    count > 0
  )
    launch.count = Math.min(count, MAX_COUNT);
  if (input.skill === 'docgen' || input.skill === 'quiz') {
    const topic = cleanTopic(input.topic);
    if (topic) launch.topic = topic;
  }
  if (typeof input.materialId === 'string' && input.materialId.length <= 128)
    launch.materialId = input.materialId;
  return launch;
};

export const skillName = (skill: LaunchableSkill): string =>
  SKILL_CATALOG[skill].name;

/** Short label for the call's "Opening …" banner and chips. */
export const skillTitle = (skill: LaunchableSkill): string =>
  SKILL_CATALOG[skill].name
    .replace(/^(?:the|your) /, '')
    .replace(/^./, c => c.toUpperCase());

/** The one line LAFINA says before the call ends and the skill opens. */
export const handoffLine = (
  launch: SkillLaunch,
  options: {online: boolean; pomodoroRunning?: boolean} = {online: true},
): string => {
  const name = skillName(launch.skill);
  const needsOnline = SKILL_CATALOG[launch.skill].online && !options.online;
  const onlineNote = needsOnline
    ? ' It needs Online Mode, so you can sign in or connect there.'
    : '';
  switch (launch.skill) {
    case 'pomodoro':
      if (options.pomodoroRunning)
        return 'You already have a focus session running. Opening it now.';
      if (launch.action === 'start')
        return 'Got it, starting a 25-minute focus session.';
      if (launch.action === 'break')
        return launch.breakKind === 'long'
          ? 'Got it, starting a 15-minute break.'
          : 'Got it, starting a 5-minute break.';
      return 'Got it, opening Pomodoro.';
    case 'flashcards':
      if (launch.action === 'review') return 'Got it, opening your flashcards.';
      if (launch.action === 'create')
        return launch.materialId
          ? 'Got it. I picked your lesson in Flashcards, just tap Generate.'
          : 'Got it. Just upload your material in Flashcards.';
      return 'Got it, opening Flashcards.';
    case 'quiz':
      return launch.action === 'create'
        ? launch.materialId
          ? 'Got it. I picked your lesson in the Quiz maker, just tap Generate.'
          : "Got it. Upload your material and I'll build the quiz."
        : 'Got it, opening the Quiz maker.';
    case 'summarizer':
      return `Got it. Opening the Summarizer, pick what to summarize.${onlineNote}`;
    case 'materials':
      return 'Got it, opening Lesson Q&A. You can upload a lesson there.';
    case 'docgen':
      return launch.topic
        ? `Got it. I put your topic in Create with LAFINA, just tap Generate.${onlineNote}`
        : `Got it, opening Create with LAFINA.${onlineNote}`;
    case 'meetings':
      return "Got it, opening Meetings. Tap record when you're ready.";
    default:
      return `Got it, opening ${name}.`;
  }
};
